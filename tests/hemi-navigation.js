const { chromium } = require('playwright'); const fs = require('fs'); const { DEP, PAGE } = require('./lib'); const { settingsOpen } = require('./lib');
const ok = (c, m) => console.log((c ? 'ok   ' : 'FAIL ') + m);
const lblAt = (pg, code, dy) => pg.evaluate(([code, dy]) => { const l = [...document.querySelectorAll('#hlabels .lbl')].find(d => d.querySelector('.code') && d.querySelector('.code').textContent === code); const r = l.getBoundingClientRect(); return [r.x + r.width / 2, r.y + dy]; }, [code, dy]);
(async () => {
  const b = await chromium.launch(); const cx = await b.newContext({ viewport: { width: 1440, height: 900 } });
  await cx.route('https://cdn.jsdelivr.net/**', r => { const u = new URL(r.request().url()); r.fulfill({ body: fs.readFileSync(DEP + u.pathname.replace('/npm/three@0.128.0', '')), contentType: 'application/javascript' }); });
  await cx.route('https://fonts.**/**', r => r.abort());
  const pg = await cx.newPage(); const errs = []; pg.on('pageerror', e => errs.push(e.stack));
  await pg.goto(PAGE); await pg.waitForTimeout(2500); await settingsOpen(pg);
  await pg.click('#btnModel'); await pg.click('#ctx button:has-text("Café")'); await pg.waitForTimeout(800);
  await pg.click('#vHemi'); await pg.waitForTimeout(1300);
  await pg.click('#btnNested'); await pg.waitForTimeout(600);
  const p = await lblAt(pg, '1C', -22);
  await pg.mouse.move(p[0], p[1]);
  for (let i = 0; i < 16; i++) { await pg.mouse.wheel(0, -160); await pg.waitForTimeout(60); }
  await pg.waitForTimeout(500);
  await pg.screenshot({ path: process.env.SP + '/shots/h-zoom.png' });
  ok(!/Brewing/.test(await pg.evaluate(() => document.getElementById('crumbs').textContent + ' ' + document.getElementById('levelName').value)), 'zooming does not jump levels in the Orthogonal view');
  await pg.click('#btnRecentre'); await pg.waitForTimeout(900);
  const q = await lblAt(pg, '1C', 6);
  await pg.mouse.click(q[0], q[1]); await pg.waitForTimeout(500);
  console.log('single click selects:', await pg.textContent('#iKind'), await pg.inputValue('#iName'));
  await pg.screenshot({ path: process.env.SP + '/shots/h-click.png' });
  await pg.keyboard.press('Escape'); await pg.waitForTimeout(300);
  await pg.mouse.dblclick(q[0], q[1]); await pg.waitForTimeout(1600);
  ok(/Brewing/.test(await pg.evaluate(() => document.getElementById('crumbs').textContent + ' ' + document.getElementById('levelName').value)), 'double-click opens the lower level: ' + await pg.evaluate(() => document.getElementById('crumbs').textContent + ' ' + document.getElementById('levelName').value));
  await pg.screenshot({ path: process.env.SP + '/shots/h-l1.png' });
  await pg.click('#upBtn'); await pg.waitForTimeout(1600);
  ok(!/Brewing/.test(await pg.textContent('#levelChip')), 'Up returns');
  const s5 = await lblAt(pg, '5', 0);
  await pg.mouse.click(s5[0] - 40, s5[1] - 10, { button: 'right' }); await pg.waitForTimeout(300);
  const menu = await pg.textContent('#ctx');
  ok(/Centre here/.test(menu), 'right-click menu works: ' + menu.slice(0, 60));
  await pg.keyboard.press('Escape');
  await pg.reload(); await pg.waitForTimeout(2500);
  ok(await pg.$eval('#vHemi', e => e.getAttribute('aria-pressed') === 'true') && (await pg.$$('#hlabels .lbl')).length > 10, 'convention persists after reload');
  console.log('errors', errs);
  await b.close();
})();
