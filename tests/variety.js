// v1.7 variety engineering: selecting a channel reveals its attenuator and amplifier; each can be named;
// Beer's symbols or words; the Triple Index on operations, read side by side at System Three.
const { chromium } = require('playwright'); const { PAGE, settingsOpen } = require('./lib');
const ok = (c, m) => console.log((c ? 'ok   ' : 'FAIL ') + m);
(async () => {
  const b = await chromium.launch(); const errs = [];
  const cx = await b.newContext({ viewport: { width: 1360, height: 860 } });
  await cx.route('https://fonts.**/**', r => r.abort());
  const pg = await cx.newPage(); pg.on('pageerror', e => errs.push(e.stack));
  await pg.goto(PAGE); await pg.waitForTimeout(1800);
  await pg.click('#wExamples [data-ex="cafeServices"]'); await pg.waitForTimeout(1500);
  await settingsOpen(pg);
  const shown = () => pg.$$eval('#labels .vg', vs => vs.filter(v => v.style.visibility !== 'hidden').map(v => v.className));
  ok((await shown()).length === 0, 'no glyphs while nothing is selected');
  const sel = async id => { await pg.evaluate(id => { const r = document.querySelector('.erow[data-id="' + id + '"] .ecode'); if (r) r.click(); }, id); await pg.waitForTimeout(500); };
  await sel('eo0');
  let g = await shown();
  ok(g.length === 2 && g.some(c => /att/.test(c)) && g.some(c => /amp/.test(c)), 'selecting environment to operation shows one attenuator and one amplifier (' + g.join(', ') + ')');
  ok(await pg.isVisible('#iVarSec'), 'the details list the pair');
  await pg.fill('#iVar input[data-v="abatt"]', 'Fixed menu'); await pg.waitForTimeout(400);
  ok((await pg.$$eval('#labels .vg .vn', v => v.map(x => x.textContent))).includes('Fixed menu'), 'a named attenuator shows its name on the channel');
  await pg.screenshot({ path: process.env.SP + '/shots/variety-eo.png' });
  await sel('h34');
  g = await shown();
  ok(g.length === 2 && g.every(c => /amp/.test(c)), 'the Three-Four homeostat shows an amplifier each way');
  await pg.screenshot({ path: process.env.SP + '/shots/variety-h34.png' });
  await sel('ee0');
  ok((await shown()).length === 0 && await pg.isHidden('#iVarSec'), 'environmental intersects carry no pair');
  await pg.click('#vnWords'); await pg.waitForTimeout(300); await sel('om1');
  const words = await pg.$$eval('#labels .vg', vs => vs.filter(v => v.style.visibility !== 'hidden').map(v => (v.querySelector('.w') || {}).textContent).sort().join());
  ok(words === 'boosts,filters', 'Words shows filters and boosts (' + words + ')');
  await pg.screenshot({ path: process.env.SP + '/shots/variety-words.png' });
  await pg.click('#vnBeer'); await pg.waitForTimeout(300);
  await sel('o0');
  ok(await pg.isVisible('#iTixSec'), 'an operation has a Triple Index');
  await pg.fill('#iTix [data-t="a"]', '17000'); await pg.fill('#iTix [data-t="c"]', '18000'); await pg.fill('#iTix [data-t="p"]', '20000');
  await pg.waitForTimeout(300);
  const out = (await pg.textContent('#iTixOut')).replace(/\s+/g, ' ');
  ok(/0\.94/.test(out) && /0\.90/.test(out) && /0\.85/.test(out), 'productivity 0.94, latency 0.90, performance 0.85');
  await sel('s3');
  const t3 = (await pg.textContent('#iTix')).replace(/\s+/g, ' ');
  ok(/0\.85/.test(t3) && (await pg.$$('#iTix .tixr tr')).length === 4, 'System Three reads every operation\'s index side by side');
  await pg.screenshot({ path: process.env.SP + '/shots/variety-s3.png' });
  const saved = await pg.evaluate(() => { const d = JSON.parse(localStorage.getItem('vsm-explorer:v1')).db; return d.levels[d.currentId]; });
  ok(saved.tix && saved.tix.o0 && saved.tix.o0.p === 20000 && saved.vari && saved.vari.eo0 && saved.vari.eo0.abatt === 'Fixed menu', 'the figures and names are saved with the level');
  await pg.click('#v3d'); await pg.waitForTimeout(1600); await sel('om0');
  ok((await shown()).length === 2, 'the pair shows in 3D too');
  await pg.screenshot({ path: process.env.SP + '/shots/variety-3d.png' });
  errs.forEach(e => console.log('page error: ' + e));
  await b.close();
})();
